const IDIOMA_PADRAO = "pt";

/** Traduz uma chave, interpolando `{param}`. Cai no pt e, por fim, na própria chave. */
export function t(idioma, chave, params = {}) {
  const dict = MENSAGENS[idioma] || MENSAGENS[IDIOMA_PADRAO];
  let texto = dict[chave] ?? MENSAGENS[IDIOMA_PADRAO][chave] ?? chave;
  return texto.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** Mapeia o idioma do navegador para um dos suportados (default pt). */
export function resolverIdioma(idiomaNavegador) {
  const l = String(idiomaNavegador || "").toLowerCase();
  if (l.startsWith("es")) return "es";
  if (l.startsWith("en")) return "en";
  return "pt";
}

