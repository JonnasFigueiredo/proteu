/** Aplica a máscara 00000-000. */
export function mascararCep(cep) {
  return String(cep).replace(/\D/g, "").replace(/^(\d{5})(\d{3})$/, "$1-$2");
}

/** Descobre a UF de um CEP pela faixa principal; null se fora de todas. */
export function ufDoCep(cep) {
  const limpo = String(cep).replace(/\D/g, "");
  if (limpo.length !== 8) return null;
  const milhar = Number(limpo.slice(0, 5));
  for (const [uf, [ini, fim]] of Object.entries(FAIXAS_UF)) {
    if (milhar >= ini && milhar <= fim) return uf;
  }
  return null;
}

/** UFs que têm CEP real disponível. */
export const UFS_COM_CEP = Object.keys(CEPS_REAIS);

/**
 * Gera um CEP coerente com a UF pedida (ou uma UF sorteada).
 *
 * Por padrão devolve um CEP que EXISTE. `sintetico: true` volta ao sorteio
 * dentro da faixa — útil só para exercitar o caminho de erro de quem valida.
 *
 * @param {object} rng
 * @param {{uf?: string, mascara?: boolean, sintetico?: boolean}} [opcoes]
 */
export function gerarCep(rng, { uf = null, mascara = false, sintetico = false } = {}) {
  const escolhida = uf ? uf.toUpperCase() : rng.escolher(UFS_COM_CEP);

  if (sintetico) {
    const faixa = FAIXAS_UF[escolhida];
    if (!faixa) throw new Error(`UF desconhecida: ${uf}`);
    const milhar = rng.inteiro(faixa[0], faixa[1]);
    const sufixo = rng.inteiro(0, 999);
    const cru = String(milhar).padStart(5, "0") + String(sufixo).padStart(3, "0");
    return mascara ? mascararCep(cru) : cru;
  }

  const reais = CEPS_REAIS[escolhida];
  if (!reais) throw new Error(`UF desconhecida: ${uf}`);
  const cru = rng.escolher(reais);
  return mascara ? mascararCep(cru) : cru;
}
